#include "delay.h"

/*============================================================================
 * 微秒延时（基于指令循环）
 *============================================================================*/
void delay_us(uint32_t nus)
{
    /* 72MHz 主频下，粗略延时 */
    for (uint32_t i = 0; i < nus * 8; i++)
    {
        __NOP();
    }
}

/*============================================================================
 * 毫秒延时（基于 SysTick）
 *============================================================================*/
void delay_ms(uint32_t nms)
{
    extern volatile uint32_t g_msTicks;
    uint32_t start = g_msTicks;
    while ((g_msTicks - start) < nms);
}

/*============================================================================
 * 简单循环延时（禁用优化）
 *============================================================================*/
__attribute__((optimize("-O0")))
void delay(uint32_t nus)
{
    while (nus--);
}

